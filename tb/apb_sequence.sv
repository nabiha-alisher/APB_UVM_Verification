//=========================================================================
// 6. WRITE FOLLOWED BY READ
//=========================================================================

class write_read_sequence extends uvm_sequence #(apb_seq_item);

  `uvm_object_utils(write_read_sequence)

  function new(string name = "write_read_sequence");
    super.new(name);
  endfunction

  virtual task body();

    logic [31:0] addr;

    // WRITE
    `uvm_do_with(req, {
      PWRITE == 1'b1;
      PSTRB  == 8'hFF;
    })

    // Save the address generated by the write.
    addr = req.PADDR;

    // READ FROM THE SAME ADDRESS
    `uvm_do_with(req, {
      PWRITE == 1'b0;
      PADDR  == addr;
    })

  endtask

endclass


//=========================================================================
// 7. RANDOM WRITE FOLLOWED BY RANDOM READ
//=========================================================================

class random_write_read_sequence extends uvm_sequence #(apb_seq_item);

  `uvm_object_utils(random_write_read_sequence)

  function new(string name = "random_write_read_sequence");
    super.new(name);
  endfunction

  virtual task body();

    logic [31:0] addr;

    repeat (20) begin

      // RANDOM WRITE
      `uvm_do_with(req, {
        PWRITE == 1'b1;
      })

      // Save write address.
      addr = req.PADDR;

      // READ FROM THE SAME ADDRESS
      `uvm_do_with(req, {
        PWRITE == 1'b0;
        PADDR  == addr;
      })

    end

  endtask

endclass


//=========================================================================
// 8. MEMORY INITIALIZATION SEQUENCE
//=========================================================================
//
// 64 KB memory / 8 bytes = 8192 locations
//
// All locations are initialized with zero.
//
//=========================================================================

class memory_init_sequence extends uvm_sequence #(apb_seq_item);

  `uvm_object_utils(memory_init_sequence)

  function new(string name = "memory_init_sequence");
    super.new(name);
  endfunction

  virtual task body();

    for (int i = 0; i < 8192; i++) begin

      `uvm_do_with(req, {
        PADDR  == (`APB_BASE_ADDR + (i * 8));
        PWRITE == 1'b1;
        PWDATA == 64'h0000_0000_0000_0000;
        PSTRB  == 8'hFF;
      })

    end

    `uvm_info("MEM_INIT",
              "64 KB memory initialization completed",
              UVM_LOW)

  endtask

endclass


//=========================================================================
