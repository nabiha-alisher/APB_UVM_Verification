//=========================================================================
// 10. BYTE STROBE SEQUENCE
//=========================================================================
//
// Tests each individual byte enable.
//
// 0000_0001
// 0000_0010
// 0000_0100
// 0000_1000
// 0001_0000
// 0010_0000
// 0100_0000
// 1000_0000
//
//=========================================================================

class byte_strobe_sequence extends uvm_sequence #(apb_seq_item);

  `uvm_object_utils(byte_strobe_sequence)

  function new(string name = "byte_strobe_sequence");
    super.new(name);
  endfunction

  virtual task body();

    for (int i = 0; i < 8; i++) begin

      `uvm_do_with(req, {
        PWRITE == 1'b1;
        PSTRB  == (8'b0000_0001 << i);
      })

    end

  endtask

endclass


//=========================================================================
// 11. BOUNDARY ADDRESS SEQUENCE
//=========================================================================
//
// First valid aligned address:
//     APB_BASE_ADDR
//
// Last valid aligned 64-bit address:
//     APB_BASE_ADDR + 0xFFF8
//
//=========================================================================

class boundary_sequence extends uvm_sequence #(apb_seq_item);

  `uvm_object_utils(boundary_sequence)

  function new(string name = "boundary_sequence");
    super.new(name);
  endfunction

  virtual task body();

    // FIRST VALID ADDRESS
    `uvm_do_with(req, {
      PADDR  == `APB_BASE_ADDR;
      PWRITE == 1'b1;
      PWDATA == 64'h1111_1111_1111_1111;
      PSTRB  == 8'hFF;
    })

    // LAST VALID ALIGNED ADDRESS
    `uvm_do_with(req, {
      PADDR  == (`APB_BASE_ADDR + 32'h0000_FFF8);
      PWRITE == 1'b1;
      PWDATA == 64'hAAAA_BBBB_CCCC_DDDD;
      PSTRB  == 8'hFF;
    })

  endtask

endclass


//=========================================================================
// 12. INVALID ADDRESS SEQUENCE
//=========================================================================
//
// First address outside the 64 KB memory range:
//     APB_BASE_ADDR + 0x10000
//
// Expected:
//     PSLVERR = 1
//
// Direct assignment is used to deliberately generate an invalid address.
// This avoids randomization constraints preventing the illegal transaction.
//
//=========================================================================

class invalid_address_sequence extends uvm_sequence #(apb_seq_item);

  `uvm_object_utils(invalid_address_sequence)

  function new(string name = "invalid_address_sequence");
    super.new(name);
  endfunction

  virtual task body();

    req = apb_seq_item::type_id::create("req");

    start_item(req);

    req.PADDR  = `APB_BASE_ADDR + 32'h0001_0000;
    req.PWRITE = 1'b1;
    req.PWDATA = 64'hDEAD_BEEF_DEAD_BEEF;
    req.PSTRB  = 8'hFF;

    finish_item(req);

    `uvm_info("INVALID_ADDR",
              "Invalid address transaction sent. PSLVERR expected.",
              UVM_LOW)

  endtask

endclass


//=========================================================================
// 13. MISALIGNED ADDRESS SEQUENCE
//=========================================================================
//
// APB access must be 8-byte aligned.
//
// Invalid addresses:
//     BASE_ADDR + 1
//     BASE_ADDR + 2
//     ...
//     BASE_ADDR + 7
//
// Expected:
//     PSLVERR = 1
//
// Direct assignment is used to deliberately generate misaligned addresses.
//
//=========================================================================

class misaligned_sequence extends uvm_sequence #(apb_seq_item);

  `uvm_object_utils(misaligned_sequence)

  function new(string name = "misaligned_sequence");
    super.new(name);
  endfunction

  virtual task body();

    for (int i = 1; i <= 7; i++) begin

      req = apb_seq_item::type_id::create("req");

      start_item(req);

      req.PADDR  = `APB_BASE_ADDR + i;
      req.PWRITE = 1'b1;
      req.PWDATA = 64'h1234_5678_9ABC_DEF0;
      req.PSTRB  = 8'hFF;

      finish_item(req);

    end

    `uvm_info("MISALIGNED",
              "Misaligned transactions sent. PSLVERR expected.",
              UVM_LOW)

  endtask

endclass


//=========================================================================
// 14. APB PROTOCOL / BACK-TO-BACK SEQUENCE
//=========================================================================
//
// Generates consecutive APB transactions.
//
// Driver should generate:
//
//       IDLE
//         |
//       SETUP
//         |
//       ACCESS
//         |
//       IDLE
//         |
//       SETUP
//         |
//       ACCESS
//
//=========================================================================

class protocol_sequence extends uvm_sequence #(apb_seq_item);

  `uvm_object_utils(protocol_sequence)

  function new(string name = "protocol_sequence");
    super.new(name);
  endfunction

  virtual task body();

    repeat (10) begin

      `uvm_do(req)

    end

    `uvm_info("PROTOCOL",
              "Back-to-back APB transactions completed",
              UVM_LOW)

  endtask

endclass

